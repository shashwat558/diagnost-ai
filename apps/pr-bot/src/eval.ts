/**
 * Eval runner + promotion gate.
 *
 * A patch ships only if it strictly improves the target set (cases derived
 * from the failing cluster) AND regresses nothing on the held-out set
 * (previously-passing conversations of the same intent).
 */
import type { AgentSimulator } from "./simulate.js";
import { grade, type EvalCase } from "./cases.js";

export interface CaseResult {
  caseId: string;
  kind: string;
  pass: boolean;
  response: string;
  sourceConversationId: string | null;
}

export interface EvalReport {
  baseline: {
    passRate: number;
    results: CaseResult[];
  };
  patched: {
    passRate: number;
    results: CaseResult[];
  };
  heldOut: {
    baselinePassRate: number;
    patchedPassRate: number;
    regressions: Array<{ caseId: string; input: string }>;
    size: number;
  };
  gate: {
    passed: boolean;
    reasons: string[];
  };
}

export async function runEval(
  simulator: AgentSimulator,
  promptText: string,
  cases: EvalCase[]
): Promise<CaseResult[]> {
  const out: CaseResult[] = [];
  for (const c of cases) {
    const response = await simulator.simulate(promptText, c.input);
    out.push({
      caseId: c.id,
      kind: c.kind,
      pass: grade(c, response),
      response,
      sourceConversationId: c.sourceConversationId,
    });
  }
  return out;
}

function passRate(results: CaseResult[]): number {
  if (results.length === 0) return 0;
  return results.filter((r) => r.pass).length / results.length;
}

export function gate(params: {
  baselineResults: CaseResult[];
  patchedResults: CaseResult[];
  heldOutBaseline: CaseResult[];
  heldOutPatched: CaseResult[];
}): { passed: boolean; reasons: string[] } {
  const reasons: string[] = [];

  const base = passRate(params.baselineResults);
  const patched = passRate(params.patchedResults);
  if (patched <= base) {
    reasons.push(`no improvement: ${base.toFixed(2)} → ${patched.toFixed(2)}`);
  }

  const regressions = params.heldOutPatched
    .map((r, i) => ({ r, before: params.heldOutBaseline[i] }))
    .filter(({ r, before }) => before?.pass && !r.pass)
    .map(({ r }) => ({ caseId: r.caseId, input: r.response.slice(0, 80) }));
  if (regressions.length > 0) {
    reasons.push(`${regressions.length} regression(s) on held-out set`);
  }

  if (params.baselineResults.length === 0) {
    reasons.push("no target cases generated");
  }

  return { passed: reasons.length === 0, reasons };
}

/** Markdown report embedded in the PR body. */
export function renderReportMarkdown(
  report: EvalReport,
  meta: { clusterIntent: string; artifactName: string; baseVersion: string; proposedVersion: string }
): string {
  const lines: string[] = [];
  lines.push(`## Eval report — ${meta.artifactName} (${meta.baseVersion} → ${meta.proposedVersion})`);
  lines.push("");
  lines.push(`Failure cluster intent: \`${meta.clusterIntent}\``);
  lines.push("");
  lines.push("| Suite | Baseline | Patched | Δ |");
  lines.push("|---|---|---|---|");
  lines.push(
    `| Target (failing-cluster cases) | ${(report.baseline.passRate * 100).toFixed(0)}% | ` +
      `${(report.patched.passRate * 100).toFixed(0)}% | ` +
      `${((report.patched.passRate - report.baseline.passRate) * 100).toFixed(0)}pp |`
  );
  lines.push(
    `| Held-out (regression set, n=${report.heldOut.size}) | ` +
      `${(report.heldOut.baselinePassRate * 100).toFixed(0)}% | ` +
      `${(report.heldOut.patchedPassRate * 100).toFixed(0)}% | ` +
      `${((report.heldOut.patchedPassRate - report.heldOut.baselinePassRate) * 100).toFixed(0)}pp |`
  );
  lines.push("");
  lines.push("**Gate**: " + (report.gate.passed ? "✅ PASSED — improvement, zero regressions" : `❌ ${report.gate.reasons.join("; ")}`));
  lines.push("");

  const fixed = report.patched.results.filter((r) => r.pass && !report.baseline.results.find((b) => b.caseId === r.caseId)?.pass);
  if (fixed.length > 0) {
    lines.push("### Cases fixed by the patch");
    for (const f of fixed) lines.push(`- \`${f.caseId}\` (${f.kind})`);
    lines.push("");
  }
  lines.push("_Auto-generated by diagnost pr-bot. Source conversations are linked in the remediation record._");
  return lines.join("\n");
}
